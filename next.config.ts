import type { NextConfig } from "next";

// 2026-07-10 (auditoría de seguridad): headers que faltaban (CSP, X-Frame-Options,
// X-Content-Type-Options). HSTS ya lo agrega Vercel. La CSP es pragmática: bloquea
// clickjacking (frame-ancestors) y limita orígenes, permitiendo lo que la app usa
// (estilos inline, conexión a Supabase, fuentes self-hosteadas de next/font).
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: https:",
  "font-src 'self' data:",
  "connect-src 'self' https://*.supabase.co",
  "frame-src 'none'",
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
];

const nextConfig: NextConfig = {
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
